import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import type { Plugin } from "vite";

const CACHE_PREFIX = "frak-referral-demo-";
const SW_FILE = "sw.js";

function listPublicFiles(dir: string): string[] {
    const files: string[] = [];
    const walk = (current: string) => {
        for (const entry of readdirSync(current)) {
            const path = join(current, entry);
            if (statSync(path).isDirectory()) walk(path);
            else if (!entry.startsWith(".")) files.push(path);
        }
    };
    walk(dir);
    return files;
}

/**
 * Cache-first for everything same-origin: the demo must run on a plane.
 * `ignoreVary`: hosts answer with `Vary: Origin`, which a module script's request never matches.
 */
function renderServiceWorker(cacheName: string, precache: string[]): string {
    return `/* Generated by vite-plugins/offlineServiceWorker.ts */
const CACHE = ${JSON.stringify(cacheName)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
    event.waitUntil(
        caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
    );
});

self.addEventListener("activate", (event) => {
    event.waitUntil(
        caches.keys()
            .then((keys) => Promise.all(
                keys
                    .filter((key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE)
                    .map((key) => caches.delete(key))
            ))
            .then(() => self.clients.claim())
    );
});

self.addEventListener("fetch", (event) => {
    const request = event.request;
    if (request.method !== "GET") return;
    const url = new URL(request.url);
    if (url.origin !== self.location.origin) return;

    if (request.mode === "navigate") {
        event.respondWith(
            caches.match("index.html", { ignoreVary: true }).then((hit) => hit || fetch(request))
        );
        return;
    }

    event.respondWith(
        caches.match(request, { ignoreSearch: true, ignoreVary: true }).then((hit) => {
            if (hit) return hit;
            return fetch(request).then((response) => {
                if (response.ok) {
                    const copy = response.clone();
                    caches.open(CACHE).then((cache) => cache.put(request, copy));
                }
                return response;
            });
        })
    );
});
`;
}

/**
 * Emits `sw.js` precaching every file of the build (bundle + `public/`), under
 * a cache name hashed from their content so any change ships a new worker.
 */
export function offlineServiceWorker(): Plugin {
    let publicDir = "";

    return {
        name: "referral-demo:offline-service-worker",
        apply: "build",
        enforce: "post",
        configResolved(config) {
            publicDir = config.publicDir;
        },
        generateBundle(_options, bundle) {
            const hash = createHash("sha256");
            const urls = new Set<string>(["index.html"]);

            for (const [fileName, output] of Object.entries(bundle)) {
                if (fileName.endsWith(".map")) continue;
                urls.add(fileName);
                hash.update(fileName);
                hash.update(
                    output.type === "chunk" ? output.code : output.source
                );
            }

            for (const file of listPublicFiles(publicDir)) {
                const url = relative(publicDir, file).split(sep).join("/");
                urls.add(url);
                hash.update(url);
                hash.update(readFileSync(file));
            }

            const precache = [...urls].sort();
            const version = hash.digest("hex").slice(0, 12);
            this.emitFile({
                type: "asset",
                fileName: SW_FILE,
                source: renderServiceWorker(
                    `${CACHE_PREFIX}${version}`,
                    precache
                ),
            });
        },
    };
}
